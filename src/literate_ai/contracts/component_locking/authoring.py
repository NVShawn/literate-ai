COMPONENT_CONTENT_SELECTOR_SCHEMA = (
    "urn:literate-ai:schema:v2:component-content-selector"
)
COMPONENT_AUTHORING_SCHEMA = "urn:literate-ai:schema:v2:component-authoring"
COMPONENT_ASSET_SELECTOR_SCHEMA = "urn:literate-ai:schema:v2:component-asset-selector"


def _asset_source(value: object, path: str) -> str:
    raw = string_value(value, path, max_length=8192)
    parsed = urlsplit(raw)
    if parsed.scheme:
        if parsed.scheme not in {"http", "https", "project"}:
            fail(path, "must use a relative path, project:/// URI, or HTTP(S) URI")
        if parsed.fragment:
            fail(path, "must not contain a URI fragment")
        if parsed.scheme == "project":
            if parsed.netloc or parsed.query or not parsed.path.startswith("/"):
                fail(path, "project URI must have the form project:///path")
            try:
                canonical_relative_posix_path(
                    parsed.path.removeprefix("/"), label="project asset path"
                )
            except (TypeError, ValueError) as exc:
                fail(path, str(exc))
        elif not parsed.netloc or parsed.username is not None:
            fail(path, "HTTP(S) URI must name a host and must not embed credentials")
        return raw
    try:
        canonical_relative_posix_path(raw, label="component asset source")
    except (TypeError, ValueError) as exc:
        fail(path, str(exc))
    return raw


@dataclass(frozen=True, slots=True)
class ComponentAssetSelector:
    """Human-owned location and runtime projection for non-generated bytes."""

    asset_id: str
    source: str
    path: str
    role: str
    media_type: str = "application/octet-stream"
    pin: ContentIdentity | None = None

    SCHEMA: ClassVar[str] = COMPONENT_ASSET_SELECTOR_SCHEMA

    def __post_init__(self) -> None:
        portable_name(self.asset_id, "ComponentAssetSelector.asset_id")
        _asset_source(self.source, "ComponentAssetSelector.source")
        try:
            canonical_relative_posix_path(self.path, label="component asset path")
        except (TypeError, ValueError) as exc:
            fail("ComponentAssetSelector.path", str(exc))
        portable_name(self.role, "ComponentAssetSelector.role")
        string_value(self.media_type, "ComponentAssetSelector.media_type")
        if not isinstance(self.pin, (ContentIdentity, type(None))):
            fail("ComponentAssetSelector.pin", "must be a ContentIdentity or null")

    @property
    def identity(self) -> ContentIdentity:
        return contract_identity(self)

    def to_dict(self) -> dict[str, object]:
        value: dict[str, object] = {
            "schema": self.SCHEMA,
            "asset_id": self.asset_id,
            "source": self.source,
            "path": self.path,
            "role": self.role,
            "media_type": self.media_type,
            "pin": None if self.pin is None else self.pin.to_dict(),
        }
        return value

    @classmethod
    def from_dict(
        cls, value: Any, *, path: str = "ComponentAssetSelector"
    ) -> ComponentAssetSelector:
        data = contract_fields(
            value,
            path=path,
            schema_uri=cls.SCHEMA,
            required=frozenset(
                {"asset_id", "source", "path", "role", "media_type", "pin"}
            ),
        )
        pin = data["pin"]
        return cls(
            asset_id=portable_name(data["asset_id"], f"{path}.asset_id"),
            source=_asset_source(data["source"], f"{path}.source"),
            path=string_value(data["path"], f"{path}.path"),
            role=portable_name(data["role"], f"{path}.role"),
            media_type=string_value(data["media_type"], f"{path}.media_type"),
            pin=(
                None
                if pin is None
                else ContentIdentity.from_dict(pin, path=f"{path}.pin")
            ),
        )


def _canonical(
    values: object,
    *,
    path: str,
    expected_type: type[Any],
    key: Any,
    label: str,
) -> tuple[Any, ...]:
    items = tuple_value(values, path)
    if len(items) > 256 or any(not isinstance(item, expected_type) for item in items):
        fail(path, f"must contain at most 256 {label} values")
    keys = tuple(key(item) for item in items)
    unique(keys, path, label)
    if keys != tuple(sorted(keys)):
        fail(path, f"must use canonical {label} order")
    return items


def _catalog_relative_uri(value: object, path: str) -> str:
    raw = string_value(value, path, max_length=4096)
    candidate = PurePosixPath(raw)
    if (
        candidate.is_absolute()
        or "\\" in raw
        or "://" in raw
        or any(character.isspace() for character in raw)
        or any(part in {"", ".", ".."} for part in candidate.parts)
        or candidate.as_posix() != raw
    ):
        fail(path, "must be a canonical catalog-relative POSIX path")
    return raw


